#!/usr/bin/env bash
# Generates the Ansible inventory for an environment by reading the IP
# from the matching Pulumi stack output.
#
# Usage:
#   ./gen-inventory.sh <development|staging|stress-test|production>
#
# Requires: pulumi CLI (logged in) — or set MERB_SERVER_HOST to skip Pulumi
# (e.g. in CI: MERB_SERVER_HOST=203.0.113.10 ./gen-inventory.sh staging).

set -euo pipefail

ENV="${1:-}"
case "$ENV" in
  development | staging | stress-test | production) ;;
  *)
    echo "Usage: $0 <development|staging|stress-test|production>" >&2
    exit 1
    ;;
esac

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
INV_DIR="$SCRIPT_DIR/../ansible/inventory/$ENV"
mkdir -p "$INV_DIR"

if [[ -n "${MERB_SERVER_HOST:-}" ]]; then
  IP="$MERB_SERVER_HOST"
  echo "Using MERB_SERVER_HOST=$IP"
else
  echo "Reading IP from Pulumi stack '$ENV'..."
  IP="$(
    cd "$SCRIPT_DIR/../pulumi" &&
      pulumi stack output ip --stack "$ENV" 2>/dev/null ||
      { echo "error: cannot read Pulumi output. Is the stack created? (cd infra/pulumi && pulumi stack select $ENV && pulumi up)" >&2; exit 1; }
  )"
fi

if [[ -z "$IP" ]]; then
  echo "error: empty IP" >&2
  exit 1
fi

cat > "$INV_DIR/hosts.auto.yml" <<EOF
---
# AUTO-GENERATED by infra/scripts/gen-inventory.sh — do not edit or commit.
all:
  children:
    merb_servers:
      hosts:
        merb-1:
          ansible_host: $IP
EOF

echo "✓ inventory/$ENV/hosts.auto.yml → $IP"
